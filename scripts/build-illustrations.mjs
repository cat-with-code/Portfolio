// Turns Light/Dark SVG exports of Figma illustrations (design/illustrations/raw/<key>.<light|dark>.svg)
// into React components whose colours are the Figma colour tokens (var(--color-…)), so one
// illustration follows the theme. Run: npm run illustrations
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const rawDir = resolve(root, "design/illustrations/raw");
const outDir = resolve(root, "src/components/illustrations");
const tokens = JSON.parse(readFileSync(resolve(root, "design/tokens.json"), "utf8"));

// Light/Dark hex pair → semantic token
const prim = new Map(tokens.primitives.map(([n, , v]) => [n, v.toUpperCase()]));
const resolveVal = (v) => (v.startsWith("@") ? prim.get(v.slice(1)) ?? resolveVal(tokens.semantic.find(([n]) => n === v.slice(1))[2]) : v.toUpperCase());
const pairs = new Map();
for (const [name, css, light, dark] of tokens.semantic) {
  if (name.startsWith("deprecated")) continue;
  const key = `${resolveVal(light)}|${resolveVal(dark)}`;
  if (!pairs.has(key)) pairs.set(key, css ?? `--${name.replaceAll("/", "-")}`);
}

const colorAttr = /(fill|stroke|stop-color|flood-color)="(#[0-9A-Fa-f]{6}|white|black)"/g;
const norm = (c) => (c === "white" ? "#FFFFFF" : c === "black" ? "#000000" : c.toUpperCase());
const clean = (svg) =>
  svg
    .replace(/<rect width="[\d.]+" height="[\d.]+" fill="#1E1E1E"\/>\n?/, "") // export canvas background
    .replace(/ id="TEMP export[^"]*"/g, "")
    .replace(/<g>\n?((?:.|\n)*)<\/g>\n?<defs>/, "$1<defs>"); // drop the now-empty wrapper group

const camel = (a) => (a.includes(":") ? a.replace(/:(\w)/, (_, c) => c.toUpperCase()) : a.replace(/-(\w)/g, (_, c) => c.toUpperCase()));

function toJsx(svg) {
  return svg
    .replace(/<svg([^>]*)>/, (_, attrs) => `<svg${attrs.replace(/ xmlns="[^"]*"/, "")} {...props}>`)
    .replace(/ ([a-z][a-z-]*(?::[a-z]+)?)=/g, (m, a) => ` ${camel(a)}=`)
    .replace(/ id="([^"]+)"/g, (_, id) => ` id={\`\${p}${id}\`}`)
    .replace(/="url\(#([^)]+)\)"/g, (_, id) => `={\`url(#\${p}${id})\`}`)
    .replace(/ (xlinkHref|href)="#([^"]+)"/g, (_, a, id) => ` ${a}={\`#\${p}${id}\`}`)
    .replace(/style="([^"]*)"/g, (_, s) => `style={{ ${s.split(";").filter(Boolean).map((d) => { const [k, v] = d.split(":"); return `${camel(k.trim())}: "${v.trim()}"`; }).join(", ")} }}`);
}

const pascal = (k) => k.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
const keys = [...new Set(readdirSync(rawDir).filter((f) => f.endsWith(".light.svg")).map((f) => f.replace(".light.svg", "")))];
mkdirSync(outDir, { recursive: true });
const report = [];
for (const key of keys) {
  const light = clean(readFileSync(resolve(rawDir, `${key}.light.svg`), "utf8"));
  const dark = clean(readFileSync(resolve(rawDir, `${key}.dark.svg`), "utf8"));
  const dm = [...dark.matchAll(colorAttr)];
  let i = 0;
  const unmatched = new Set();
  const merged = light.replace(colorAttr, (m, attr, c) => {
    const pair = `${norm(c)}|${norm(dm[i++]?.[2] ?? c)}`;
    const token = pairs.get(pair);
    if (token) return `${attr}="var(${token})"`;
    const [l, d] = pair.split("|");
    if (l !== d) unmatched.add(pair);
    return m; // constant colour (same in both themes) stays as exported
  });
  if (dm.length !== [...light.matchAll(colorAttr)].length) throw new Error(`${key}: light/dark structure differs`);
  const name = `${pascal(key)}Art`;
  const body = toJsx(merged.trim());
  writeFileSync(
    resolve(outDir, `${key}.tsx`),
    `"use client";\n// Generated by scripts/build-illustrations.mjs from Figma exports — do not edit by hand.\nimport { useId, type SVGProps } from "react";\n\nexport function ${name}(props: SVGProps<SVGSVGElement>) {\n  const p = useId().replace(/[^a-zA-Z0-9]/g, "");\n  return (\n    ${body.replace(/\n/g, "\n    ")}\n  );\n}\n`
  );
  report.push(`${key}: ${name}${unmatched.size ? "  ⚠ theme-changing colours with no token: " + [...unmatched].join(", ") : ""}`);
}
console.log(report.join("\n"));
