// Generates src/styles/tokens.css from design/tokens.json (exported from the Figma file).
// Run: npm run tokens
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(resolve(root, "design/tokens.json"), "utf8"));

// Figma names without a CSS code syntax get one derived the same way the others were.
const cssName = (figma, css) => css ?? `--${figma.replaceAll("/", "-")}`;
const byFigma = new Map();
for (const [figma, css] of [...t.primitives, ...t.semantic]) byFigma.set(figma, cssName(figma, css));
const value = (v) => (typeof v === "string" && v.startsWith("@") ? `var(${byFigma.get(v.slice(1))})` : v);
const px = (n) => (n === 0 ? "0" : `${n}px`);

const lines = (rows, pick) => rows.map((r) => `  ${cssName(r[0], r[1])}: ${pick(r)};`).join("\n");
const out = [];
out.push("/* Generated by scripts/build-tokens.mjs from design/tokens.json — do not edit by hand. */\n");

out.push(`:root {\n  /* Color primitives */\n${lines(t.primitives, (r) => r[2])}\n}\n`);

const light = lines(t.semantic, (r) => value(r[2]));
const dark = lines(t.semantic, (r) => value(r[3]));
out.push(`/* Color semantic — Light (default) */\n:root {\n  color-scheme: light;\n${light}\n}\n`);
out.push(`/* Color semantic — Dark: explicit choice, or System when the device prefers dark */\n:root[data-theme="dark"] {\n  color-scheme: dark;\n${dark}\n}\n`);
out.push(`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]):not([data-theme="dark"]) {\n    color-scheme: dark;\n${dark.replaceAll("\n  ", "\n    ").replace(/^  /, "    ")}\n  }\n}\n`);

out.push(`:root {\n  /* Dimensions */\n${lines(t.dimensions, (r) => (r[0].startsWith("opacity/") ? r[2] / 100 : px(r[2])))}\n\n  /* Typography */\n${lines(t.typography, (r) => px(r[2]))}\n\n  /* Motion */\n${lines(t.motion, (r) => (typeof r[2] === "number" ? `${r[2]}ms` : r[2]))}\n}\n`);

// Responsive collection: mobile-first. Mobile < 768 ≤ Tablet < 1280 ≤ Desktop.
const [dI, tI, mI] = [2, 3, 4];
const resp = (i) => lines(t.responsive, (r) => px(r[i])).replace(/--layout-columns: (\d+)px/, "--layout-columns: $1");
out.push(`/* Responsive — Mobile (default) */\n:root {\n${resp(mI)}\n}\n`);
out.push(`/* Responsive — Tablet */\n@media (min-width: 768px) {\n  :root {\n${resp(tI).replaceAll("\n  ", "\n    ").replace(/^  /, "    ")}\n  }\n}\n`);
out.push(`/* Responsive — Desktop */\n@media (min-width: 1280px) {\n  :root {\n${resp(dI).replaceAll("\n  ", "\n    ").replace(/^  /, "    ")}\n  }\n}\n`);

// Effect styles. Figma BACKGROUND_BLUR radius r renders like CSS blur(r / 2).
const fx = t.effects.map(([n, v]) => `  --${n}: ${typeof v === "number" ? px(v / 2) : v};`).join("\n");
out.push(`:root {\n  /* Effect styles */\n${fx}\n}\n`);

// Text styles → type-* utilities. Khmer pages swap the Latin styles for their Khmer counterparts.
const slug = (name) => name.toLowerCase().replaceAll("/", "-").replaceAll(" ", "-");
const utils = [];
for (const [name, family, weight, token, tracking] of t.textStyles) {
  const s = slug(name);
  const [size, lh] = Array.isArray(token)
    ? token.map(px)
    : [`var(--typography-${token.replaceAll("/", "-")}-size)`, `var(--typography-${token.replaceAll("/", "-")}-line-height)`];
  const fam = family === "Inter" ? "var(--type-family)" : "var(--font-khmer)";
  utils.push(
    `@utility type-${s} {\n  font-family: ${fam};\n  font-weight: var(--type-${s}-weight, ${weight});\n  font-size: ${size};\n  line-height: ${lh};\n  letter-spacing: ${tracking ? px(tracking) : "0"};\n}`
  );
}
out.push(`/* Font families (set by next/font in the root layout) */\n:root {\n  --type-family: var(--font-arrows), var(--font-latin), var(--font-khmer), system-ui, sans-serif;\n}\n`);
out.push(`/* Text styles */\n${utils.join("\n\n")}\n`);

const khmerSwap = [
  ["body", "khmer/body", 400],
  ["label", "khmer/label", 500],
  ["page-title", "khmer/page-title", 600],
  ["caption", "khmer/caption", 400],
  ["card-title", "khmer/card-title", 500],
];
const km = khmerSwap
  .map(
    ([latin, khmer, w]) =>
      `  --typography-${latin}-size: var(--typography-${khmer.replace("/", "-")}-size);\n  --typography-${latin}-line-height: var(--typography-${khmer.replace("/", "-")}-line-height);\n  --type-${latin}-weight: ${w};`
  )
  .join("\n");
out.push(`/* Khmer interface: same utilities, Khmer type ramp + font */\n:root:lang(km) {\n  --type-family: var(--font-arrows), var(--font-khmer), var(--font-latin);\n${km}\n}\n`);

const file = resolve(root, "src/styles/tokens.css");
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${file}`);

// Tailwind theme: utilities named after the Figma tokens.
//   color/bg/page → bg-page · color/text/secondary → text-secondary · color/icon/general/primary → text-icon-general-primary
//   color/border/general/default → border-general-default · color/study/canvas → bg-study-canvas / text-study-canvas
// Spacing is 1px per step so numbers read as Figma pixels: p-24 = 24px, w-248 = 248px.
const theme = ["/* Generated by scripts/build-tokens.mjs — do not edit by hand. */", "@theme inline {"];
theme.push("  --color-*: initial;", "  --text-*: initial;", "  --radius-*: initial;", "  --shadow-*: initial;", "  --blur-*: initial;", "  --breakpoint-*: initial;", "");
theme.push("  --spacing: 1px;", "  --breakpoint-tablet: 768px;", "  --breakpoint-desktop: 1280px;", "");
theme.push("  --font-sans: var(--type-family);", "");
for (const [figma, css] of t.semantic) {
  const v = `var(${cssName(figma, css)})`;
  const [, group, ...rest] = figma.split("/");
  const name = rest.join("-");
  if (group === "bg") theme.push(`  --background-color-${name}: ${v};`);
  else if (group === "text") theme.push(`  --text-color-${name}: ${v};`);
  else if (group === "icon") theme.push(`  --text-color-icon-${name}: ${v};`, `  --fill-icon-${name}: ${v};`);
  else if (group === "border") theme.push(`  --border-color-${name}: ${v};`, `  --outline-color-${name}: ${v};`);
  else theme.push(`  --background-color-${group}-${name}: ${v};`, `  --text-color-${group}-${name}: ${v};`, `  --border-color-${group}-${name}: ${v};`);
}
theme.push("");
for (const [figma] of t.dimensions.filter(([n]) => n.startsWith("radius/"))) {
  const n = figma.split("/")[1];
  theme.push(`  --radius-${n}: var(--radius-${n});`.replace(`--radius-${n}: var(--radius-${n})`, `--radius-${n}: ${px(t.dimensions.find(([f]) => f === figma)[2])}`));
}
theme.push("", "  --shadow-card: var(--shadow-card);".replace("var(--shadow-card)", t.effects[0][1]));
theme.push(`  --shadow-dropdown: ${t.effects[1][1]};`, `  --shadow-modal: ${t.effects[2][1]};`, `  --shadow-focus: ${t.effects[3][1]};`);
theme.push(`  --blur-backdrop: ${px(t.effects[4][1] / 2)};`, `  --blur-backdrop-light: ${px(t.effects[5][1] / 2)};`);
theme.push("", "  --ease-standard: var(--easing-standard);", "  /* Figma prototype 'Ease out' (drawers, sidebar) */", "  --ease-figma-out: cubic-bezier(0, 0, 0.58, 1);");
theme.push("}");
const themeFile = resolve(root, "src/styles/theme.css");
writeFileSync(themeFile, theme.join("\n") + "\n");
console.log(`Wrote ${themeFile}`);
